/**
 * 组装某强度的 system 提示词。
 * @param {string} mode - rewrite / augment / structure。
 * @returns {string} system 文本。
 */
export function buildSystem(mode) {
  const section = MODE_SECTIONS[mode]
  if (section === undefined) throw new Error('unknown mode: ' + String(mode))
  return [CORE, section.join('\n'), DISCIPLINE].join('\n\n')
}

/**
 * 包装用户草稿。
 *
 * 用三引号包裹并给出中性引导语：不加包装时模型常把草稿当成对话的一部分来回答，
 * 而不是当成「待改写的素材」。
 * @param {string} text - 用户草稿。
 * @param {object} [extra] - 附加材料。
 * @param {string} [extra.digest] - 会话上文摘要。
 * @param {string} [extra.previous] - 上一版结果（迭代模式）。
 * @param {string} [extra.feedback] - 用户修改意见（迭代模式）。
 * @returns {string} 用户消息文本。
 */
export function buildUser(text, extra) {
  const blocks = ['【待改写的草稿】', '"""', String(text ?? '').trim(), '"""']
  const digest = String((extra && extra.digest) || '').trim()
  if (digest !== '') blocks.push('', '【相关上文（仅作理解依据，禁止复述）】', digest)
  const previous = String((extra && extra.previous) || '').trim()
  if (previous !== '') blocks.push('', '【上一版结果】', previous)
  const feedback = String((extra && extra.feedback) || '').trim()
  if (feedback !== '') blocks.push('', '【修改意见（只按意见增量修改上一版，其余保持不变）】', feedback)
  return blocks.join('\n')
}
