// prompt-forge —— 模型侧提示词（system 文本与用户消息包装）。
//
// 来源与取舍：
//   · 语义保真五步法 / 明确化原则 / 稳定性纪律 ← dsh-prompt-enhancer 3.4.2 的 SYSTEM_PROMPT
//   · 输出纪律（只输出本体、禁前后缀、禁回显）← 同上的 DISCIPLINE_PROMPT
//   · 增量模板的「保守增量」红线 ← 同上的 SYSTEM_INCREMENT_PROMPT
//   · 结构化七段的目标形态 ← dsh-plugin-structured-prompt 0.4.0 的段落渲染
//   · 「八大板块」的板块清单 ← dsh-prompt-optimizer 1.2.0 的 spec
//
// 三者原来各写一份，规则互相冲突（一个要求输出「八大板块」、一个要求「只重述不改写」、
// 一个要求「输出七段 Markdown」）。这里统一成：**同一个内核，三种强度**——
//   rewrite  只重述 + 明确化（保守，默认）
//   augment  在 rewrite 之上保守补充「不说会导致误判」的大逻辑
//   structure 在 augment 之上产出七段结构化提示词（板块齐备，可当规格用）
//
// 无论哪种强度，输出都是**可直接使用的提示词本体**，不带任何解释、导语或代码围栏。

